(function () {
  var saved = null;
  try { saved = localStorage.getItem('ns_lang'); } catch (e) {}
  window.currentLang = saved === 'ru' || saved === 'en' ? saved : 'en';

  window.t = function (key) {
    var dict = window.I18N[window.currentLang] || window.I18N.en;
    return dict[key] || window.I18N.en[key] || key;
  };

  window.applyI18n = function () {
    document.documentElement.lang = window.currentLang;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = window.t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      el.setAttribute('placeholder', window.t(el.getAttribute('data-i18n-placeholder')));
    });
    document.querySelectorAll('.lang-switch button').forEach(function (b) {
      b.classList.toggle('active', b.dataset.lang === window.currentLang);
    });
  };

  window.setLang = function (lang) {
    window.currentLang = lang === 'ru' ? 'ru' : 'en';
    try { localStorage.setItem('ns_lang', window.currentLang); } catch (e) {}
    window.applyI18n();
    document.dispatchEvent(new CustomEvent('langchange'));
  };
})();
